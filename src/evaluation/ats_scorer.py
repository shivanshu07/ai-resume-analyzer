from typing import Any, Dict, List


class ATSScorer:
    """
    Calculates an overall ATS-style score from the
    requirement-level hybrid matching results.

    The scorer uses:

        hybrid_score
        +
        requirement importance

    rather than simply counting matched requirements.
    """

    # --------------------------------------------------------
    # Importance weights
    # --------------------------------------------------------

    IMPORTANCE_WEIGHTS = {
        "high": 1.50,
        "medium": 1.00,
        "low": 0.75
    }

    def __init__(self):
        pass

    # ========================================================
    # GET IMPORTANCE WEIGHT
    # ========================================================

    def get_importance_weight(
        self,
        result: Dict[str, Any]
    ) -> float:

        importance = str(
            result.get(
                "importance",
                "medium"
            )
        ).strip().lower()

        return self.IMPORTANCE_WEIGHTS.get(
            importance,
            self.IMPORTANCE_WEIGHTS["medium"]
        )

    # ========================================================
    # GET HYBRID SCORE
    # ========================================================

    def get_hybrid_score(
        self,
        result: Dict[str, Any]
    ) -> float:
        """
        Extract the hybrid score generated by Day 5.

        Your current hybrid_results.json stores the score
        under:

            hybrid_score

        The fallback handling makes this component safer
        if the schema changes slightly later.
        """

        score = result.get(
            "hybrid_score",
            0.0
        )

        try:
            score = float(score)
        except (
            TypeError,
            ValueError
        ):
            score = 0.0

        # ----------------------------------------------------
        # hybrid_score is already 0-1 in Day 5.
        # ----------------------------------------------------

        if score > 1:
            score = score / 100.0

        return max(
            0.0,
            min(
                score,
                1.0
            )
        )

    # ========================================================
    # CALCULATE ATS SCORE
    # ========================================================

    def calculate_score(
        self,
        results: List[Dict[str, Any]]
    ) -> float:
        """
        Calculates a weighted overall ATS score.

        Formula:

            sum(
                hybrid_score * importance_weight
            )
            /
            sum(importance_weight)

        Result is converted to a 0-100 scale.
        """

        if not results:
            return 0.0

        weighted_score = 0.0
        total_weight = 0.0

        for result in results:

            if not isinstance(
                result,
                dict
            ):
                continue

            score = self.get_hybrid_score(
                result
            )

            weight = self.get_importance_weight(
                result
            )

            weighted_score += (
                score * weight
            )

            total_weight += weight

        if total_weight == 0:
            return 0.0

        final_score = (
            weighted_score
            / total_weight
        ) * 100

        return round(
            final_score,
            2
        )

    # ========================================================
    # ASSESSMENT SUMMARY
    # ========================================================

    def summarize_assessments(
        self,
        results: List[Dict[str, Any]]
    ) -> Dict[str, int]:
        """
        Counts how many requirements fall into each
        assessment category.
        """

        summary = {
            "total": 0,
            "strong": 0,
            "partial": 0,
            "weak": 0,
            "no_alignment": 0
        }

        for result in results:

            if not isinstance(
                result,
                dict
            ):
                continue

            summary["total"] += 1

            assessment = str(
                result.get(
                    "assessment",
                    ""
                )
            ).strip().upper()

            if assessment == "STRONG_ALIGNMENT":

                summary["strong"] += 1

            elif assessment == "PARTIAL_ALIGNMENT":

                summary["partial"] += 1

            elif assessment == "WEAK_ALIGNMENT":

                summary["weak"] += 1

            elif assessment == "NO_ALIGNMENT":

                summary["no_alignment"] += 1

        return summary

    # ========================================================
    # CATEGORY SUMMARY
    # ========================================================

    def summarize_categories(
        self,
        results: List[Dict[str, Any]]
    ) -> Dict[str, Dict[str, Any]]:
        """
        Produces separate score summaries for:

            required
            preferred
            responsibility

        This is useful because a candidate can have a
        strong technical match while still having gaps
        in responsibilities.
        """

        categories = {}

        for result in results:

            category = str(
                result.get(
                    "category",
                    "other"
                )
            ).strip().lower()

            if category not in categories:

                categories[category] = []

            categories[category].append(
                result
            )

        output = {}

        for category, category_results in categories.items():

            output[category] = {
                "score": self.calculate_score(
                    category_results
                ),
                "summary": self.summarize_assessments(
                    category_results
                )
            }

        return output

    # ========================================================
    # SCORE INTERPRETATION
    # ========================================================

    def interpret_score(
        self,
        score: float
    ) -> str:
        """
        Converts the numerical score into a human-readable
        interpretation.

        These are project-level interpretations and should
        not be presented as official ATS thresholds.
        """

        if score >= 80:

            return "Strong Match"

        if score >= 65:

            return "Good Match"

        if score >= 50:

            return "Moderate Match"

        if score >= 35:

            return "Weak Match"

        return "Low Match"

    # ========================================================
    # FULL SCORE ANALYSIS
    # ========================================================

    def generate_analysis(
        self,
        results: List[Dict[str, Any]]
    ) -> Dict[str, Any]:

        score = self.calculate_score(
            results
        )

        return {
            "overall_ats_score": score,

            "score_interpretation": (
                self.interpret_score(
                    score
                )
            ),

            "requirement_summary": (
                self.summarize_assessments(
                    results
                )
            ),

            "category_summary": (
                self.summarize_categories(
                    results
                )
            )
        }